"""Build one transactional SQL Editor script from canonical migrations."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "supabase"


def build():
    # Historical migrations are immutable; new model contracts belong in new migrations.
    migrations = sorted((BASE / "migrations").glob("*.sql"))
    foundation = migrations[0].read_text(encoding="utf-8")
    # Existing six-table foundation is retained. A partially applied foundation
    # is rejected instead of silently filling a drifted schema.
    wrapper = """-- Generated by build_setup.py. Run ALL of this script ONCE in SQL Editor.
-- Supports a fresh project OR the previously applied six-table foundation.
-- Existing data is retained. Any failure rolls back this whole setup.
begin;
do $install$
declare v_count integer;
begin
  if to_regclass('public.staff_members') is not null then
    raise exception 'Workspace already installed; use new versioned migrations, not setup.sql';
  end if;
  select count(*) into v_count from information_schema.tables where table_schema='public'
    and table_name in ('customers','prediction_runs','customer_snapshots','churn_predictions','prediction_contexts','retention_cases');
  if v_count=0 then
    execute $foundation$\n""" + foundation + """\n$foundation$;
  elsif v_count<>6 then
    raise exception 'Partial foundation found. Stop and inspect schema before installing';
  end if;
end $install$;
"""
    sections = [wrapper]
    for path in migrations[1:]:
        sections += ["\n-- Source: " + path.name + "\n", path.read_text(encoding="utf-8")]
    sections.append("\nnotify pgrst, 'reload schema';\ncommit;\n")
    (BASE / "setup.sql").write_text("".join(sections), encoding="utf-8")
    print(f"Built setup.sql from {len(migrations)} migrations.")


if __name__ == "__main__":
    build()
